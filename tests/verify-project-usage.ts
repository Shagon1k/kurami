import assert from "node:assert/strict";
import {mkdtempSync,mkdirSync,writeFileSync,rmSync,symlinkSync,appendFileSync} from "node:fs";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {DatabaseSync} from "node:sqlite";
import {readProjectUsage} from "../src/orchestrator/projects/usage-read-model.ts";
import {readThreadUsage} from "../src/core/codex-usage.ts";

const home=mkdtempSync(join(tmpdir(),"kurami-project-usage-"));
try {
  const path=join(home,"orchestrator.db"),codexHome=join(home,"codex");
  mkdirSync(join(codexHome,"sessions"),{recursive:true});
  const db=new DatabaseSync(path);
  db.exec(`CREATE TABLE runs(run_id TEXT,project TEXT,item_id TEXT,state TEXT,created_at TEXT);
    CREATE TABLE run_resources(run_id TEXT,codex_thread_id TEXT,previous_codex_thread_id TEXT);
    CREATE TABLE run_state_history(run_id TEXT,to_state TEXT,reason TEXT,occurred_at TEXT,details_json TEXT);
    CREATE TABLE run_autonomous_successions(run_id TEXT,predecessor_thread_id TEXT,successor_thread_id TEXT);
    CREATE TABLE run_ai_reviews(run_id TEXT,codex_thread_id TEXT);
    CREATE TABLE run_ci_repair_attempts(run_id TEXT,codex_thread_id TEXT);
    CREATE TABLE run_review_fix_rounds(run_id TEXT,codex_thread_id TEXT);`);
  const runs=db.prepare("INSERT INTO runs VALUES(?,'p',?,?,'2026-08-01T00:00:00Z')");
  for(const [id,item,state] of [["a","one","archived"],["retry","one","cancelled"],["b","two","archived"],["missing","three","archived"],["c","four","archived"],["d","five","archived"],["old","six","archived"],["cancel","seven","cancelled"],["false","eight","archived"],["parked","nine","parked_review"]])runs.run(id,item,state);
  const history=db.prepare("INSERT INTO run_state_history VALUES(?,'archived','merged_worktree_release_completed',?,?)");
  const verified=JSON.stringify({completionVerified:true,mergeEvidence:"github_pr"});
  for(const id of ["a","missing","c","d","cancel"])history.run(id,"2026-09-29T00:00:00Z",verified);
  history.run("a","2026-09-29T01:00:00Z",verified);
  history.run("b","2026-09-10T00:00:00Z",JSON.stringify({completionVerified:true,mergeEvidence:"git_ancestry"}));
  history.run("old","2026-08-10T00:00:00Z",verified);
  history.run("old","2026-09-29T00:00:00Z",verified);
  history.run("false","2026-09-29T00:00:00Z",JSON.stringify({completionVerified:false,mergeEvidence:"github_pr"}));
  db.exec(`INSERT INTO run_resources VALUES('a','fix','main'),('retry','failed-main',NULL),('b','other',NULL),('missing','absent',NULL),('c','shared',NULL),('d','shared',NULL);
    INSERT INTO run_autonomous_successions VALUES('a','main','successor');
    INSERT INTO run_ai_reviews VALUES('a','review');
    INSERT INTO run_ci_repair_attempts VALUES('a','fix');
    INSERT INTO run_review_fix_rounds VALUES('a','fix');`);
  db.close();
  const codex=new DatabaseSync(join(codexHome,"state_5.sqlite"));
  codex.exec("CREATE TABLE threads(id TEXT,rollout_path TEXT)");
  const add=(id:string,tokens:number,at="2026-09-01T00:00:00Z")=>{
    const path=join(codexHome,"sessions",id+".jsonl");
    const record={timestamp:at,type:"event_msg",payload:{type:"token_count",info:{total_token_usage:{input_tokens:tokens,output_tokens:0,cached_input_tokens:0}}}};
    writeFileSync(path,JSON.stringify(record)+"\n");
    codex.prepare("INSERT INTO threads VALUES(?,?)").run(id,path);
    return path;
  };
  const main=add("main",100);
  add("successor",50);add("failed-main",50);add("review",25);add("fix",25);add("other",300);add("shared",20);
  appendFileSync(main,JSON.stringify({timestamp:"2026-09-29T02:00:00Z",type:"event_msg",payload:{type:"token_count",info:{total_token_usage:{input_tokens:1000,output_tokens:0,cached_input_tokens:0}}}})+"\n");
  codex.close();
  const now=new Date("2026-09-30T00:00:00Z");
  const snapshot=readProjectUsage(path,["p"],now,(ids,until)=>readThreadUsage(codexHome,ids,until));
  assert.equal(snapshot.available,true);
  assert.deepEqual(snapshot.periods[7],{completed:4,measured:1,medianTokens:250,reworkPercent:10});
  assert.equal(snapshot.periods[30].completed,5);
  assert.equal(snapshot.periods[30].measured,2);
  assert.equal(snapshot.periods[30].medianTokens,275);
  assert.equal(snapshot.periods[30].reworkPercent,100*25/550);
  assert.deepEqual(snapshot.projects.p?.[7],snapshot.periods[7]);
  const alias=new DatabaseSync(path);
  alias.exec("UPDATE run_resources SET codex_thread_id='only-repair' WHERE run_id='missing'; INSERT INTO run_ci_repair_attempts VALUES('missing','only-repair')");
  alias.close();
  const aliasSnapshot=readProjectUsage(path,["p"],now,(ids,until)=>{
    const result=readThreadUsage(codexHome,ids,until);
    if(ids.includes("only-repair"))result.set("only-repair",{tokens:50,observed:true});
    return result;
  });
  assert.deepEqual(aliasSnapshot.periods[7],snapshot.periods[7],"a temporary repair alias cannot establish complete main-session usage");
  const none=readProjectUsage(path,["p"],new Date("2026-12-30T00:00:00Z"),()=>new Map());
  assert.deepEqual(none.periods[7],{completed:0,measured:0,medianTokens:null,reworkPercent:null});
  assert.equal(readProjectUsage(join(home,"missing.db"),["p"],now,()=>new Map()).available,false);
  const escape=join(home,"outside.jsonl");writeFileSync(escape,readThreadUsage.toString());
  symlinkSync(escape,join(codexHome,"sessions","escape.jsonl"));
  const lookup=new DatabaseSync(join(codexHome,"state_5.sqlite"));
  lookup.prepare("INSERT INTO threads VALUES(?,?)").run("escape",join(codexHome,"sessions","escape.jsonl"));lookup.close();
  assert.equal(readThreadUsage(codexHome,["escape"],now).get("escape")?.tokens,null);
  assert.equal(readThreadUsage(codexHome,["main"],new Date("2026-09-02T00:00:00Z")).get("main")?.tokens,100);
  assert.equal(readThreadUsage(codexHome,["main"],now).get("main")?.tokens,1000);
  console.log("Project Usage: verified 7/30 cohorts, lifetime attempts, phase aliases, deduplication, incomplete and ambiguous logs, completion cutoff and path boundary");
}finally{rmSync(home,{recursive:true,force:true});}
