import assert from "node:assert/strict";
import {appendFileSync,mkdirSync,mkdtempSync,rmSync,writeFileSync} from "node:fs";
import {join} from "node:path";
import {tmpdir} from "node:os";
import {DatabaseSync} from "node:sqlite";
import {estimateApiEquivalent,summarizeModelUsage} from "../src/core/api-equivalent.ts";
import {collectCodexSnapshot} from "../src/hub/codex.ts";
import {estimatedUsd} from "../src/hub/format.ts";
import type {UsageEvent} from "../src/core/codex-usage.ts";

const usage=(extra:Partial<UsageEvent>={}):UsageEvent=>({at:0,input:1_000_000,cached:400_000,cacheWrite:100_000,output:100_000,total:1_100_000,model:"gpt-6-sol",requestInput:200_000,...extra});
assert.deepEqual(estimateApiEquivalent(usage()),{usd:2.33,uncertain:false});
assert.deepEqual(estimateApiEquivalent(usage({requestInput:272_000})),{usd:2.33,uncertain:false});
assert.deepEqual(estimateApiEquivalent(usage({requestInput:272_001})),{usd:4.16,uncertain:false});
assert.deepEqual(estimateApiEquivalent(usage({model:"gpt-6.1-sol"})),{usd:2.29,uncertain:false});
const uncertain=estimateApiEquivalent(usage({cacheWrite:null,requestInput:null}));
assert.equal(uncertain?.uncertain,true);assert(Math.abs(uncertain!.usd-2.28)<1e-12);
assert.equal(estimateApiEquivalent(usage({model:"codex-auto-review"})),null,"unpublished aliases do not inherit a made-up tariff");
assert.equal(estimateApiEquivalent(usage({model:null})),null);
assert.equal(estimateApiEquivalent(usage({model:"constructor"})),null);
assert.equal(estimateApiEquivalent(usage({model:"__proto__"})),null);
assert.equal(estimateApiEquivalent(usage({output:NaN})),null);
assert.equal(estimateApiEquivalent(usage({requestInput:-1})),null);
assert.equal(estimateApiEquivalent(usage({cached:1_100_000})),null);
assert.equal(estimateApiEquivalent(usage({cacheWrite:900_000})),null);
assert(estimateApiEquivalent(usage({model:"gpt-5.6-luna"})));
assert(estimateApiEquivalent(usage({model:"gpt-5.6"})));
const grouped=summarizeModelUsage([{event:usage(),session:"one"},{event:usage({model:"gpt-6.1-sol"}),session:"one"},{event:usage({cacheWrite:null}),session:"two"},{event:usage({model:null}),session:"three"}]);
assert.equal(grouped.models.length,3);
assert.equal(grouped.models[0]?.sessions,2);
assert.equal(grouped.models[0]?.cacheWrite,null);
assert.equal(grouped.equivalent.unpricedTokens,1_100_000);
assert.equal(grouped.equivalent.uncertainTokens,1_100_000);
assert.equal(grouped.equivalent.pricedTokens,3_300_000);
assert.equal(summarizeModelUsage([]).equivalent.usd,null);
assert.equal(estimatedUsd(null),"—");assert.equal(estimatedUsd(.001),"<$0.01");

const home=mkdtempSync(join(tmpdir(),"kurami-api-equivalent-"));
try {
  mkdirSync(join(home,"sessions"));
  const path=join(home,"sessions","usage.jsonl");
  const at="2026-09-01T00:00:00Z",later="2026-09-29T00:00:00Z";
  const context=(timestamp:string,model:string)=>({timestamp,type:"turn_context",payload:{model}});
  const count=(timestamp:string,total:object,last:object)=>({timestamp,type:"event_msg",payload:{type:"token_count",info:{total_token_usage:total,last_token_usage:last}}});
  const first={input_tokens:1000,cached_input_tokens:400,cache_write_input_tokens:100,output_tokens:100};
  const second={input_tokens:2000,cached_input_tokens:800,cache_write_input_tokens:200,output_tokens:200};
  writeFileSync(path,[context(at,"gpt-6-sol"),{timestamp:at,type:"token_usage_record",payload:{usage:first}},count(at,first,first),context(later,"gpt-6.1-sol"),{timestamp:later,type:"token_usage_record",payload:{usage:first}},count(later,second,first)].map(record=>JSON.stringify(record)).join("\n")+"\n");
  const db=new DatabaseSync(join(home,"state_5.sqlite"));
  db.exec("CREATE TABLE threads(created_at INTEGER,updated_at INTEGER,model TEXT,rollout_path TEXT)");
  db.prepare("INSERT INTO threads VALUES(?,?,?,?)").run(Date.parse(at)/1000,Date.parse(later)/1000,"gpt-6.1-sol",path);db.close();
  const options={home,now:new Date("2026-09-30T00:00:00Z")};
  const snapshot=collectCodexSnapshot(options);
  assert.equal(snapshot.tokens30,2200,"records and cumulative counters are not double-counted");
  assert.equal(snapshot.periods?.[30].modelUsage?.find(row=>row.name==="gpt-6-sol")?.tokens,1100,"older usage retains the original model");
  assert.equal(snapshot.periods?.[7].modelUsage?.length,1);
  assert.equal(snapshot.periods?.[7].modelUsage?.[0]?.name,"gpt-6.1-sol");
  assert(Math.abs(snapshot.periods![7].equivalent!.usd!-.00229)<1e-12);
  assert.equal(snapshot.periods?.[7].equivalent?.uncertainTokens,0);
  appendFileSync(path,JSON.stringify(count(later,{input_tokens:3000,cached_input_tokens:1200,cache_write_input_tokens:300,output_tokens:300},first))+"\n");
  const appended=collectCodexSnapshot(options);
  assert.equal(appended.tokens30,3300);assert.equal(appended.periods?.[7].modelUsage?.[0]?.tokens,2200);
  assert.equal(collectCodexSnapshot(options).tokens30,3300,"cache reuse preserves totals");
  const missing=join(home,"sessions","missing.jsonl");
  writeFileSync(missing,JSON.stringify({timestamp:later,type:"token_usage_record",payload:{usage:first}})+"\n");
  const lookup=new DatabaseSync(join(home,"state_5.sqlite"));
  lookup.prepare("INSERT INTO threads VALUES(?,?,?,?)").run(Date.parse(later)/1000,Date.parse(later)/1000,"gpt-6-sol",missing);lookup.close();
  const partial=collectCodexSnapshot(options);
  assert.equal(partial.periods?.[7].equivalent?.unpricedTokens,1100,"a thread's last model is not guessed for unlabelled usage");
  assert.equal(partial.periods?.[7].modelUsage?.find(row=>row.name==="unknown")?.equivalent.usd,null);
  console.log("API equivalent: Standard rates, cache read/write, long context, historical model changes, 7/30 windows, incremental reads and honest unknown coverage verified");
}finally{rmSync(home,{recursive:true,force:true});}
