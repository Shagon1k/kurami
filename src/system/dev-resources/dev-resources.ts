// Development resources: how much of the server Kurami's development work may take. Codex workers of every
// project, their tests and builds, and Kurami's own test runs start through bin/kurami-dev-run, which puts
// them in the kurami-dev.slice systemd user slice; everything they spawn stays inside. This module owns the
// slice limits (Hub → Controls → Server → Development resources) and the test runner's worker count.
import { existsSync, readFileSync } from "node:fs";
import { mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { cpus, homedir } from "node:os";
import { dirname, resolve } from "node:path";
import { promisify } from "node:util";
import { resolveKuramiHome } from "../../core/kurami-home.ts";

process.umask(0o077);
const run = promisify(execFile);

export const DEV_SLICE = "kurami-dev.slice";
/** Lower than the default 100 of other user units, so development yields CPU to Kurami's own services. */
export const DEV_CPU_WEIGHT = 20;
export const DEV_DEFAULTS = { cores: 4, testJobs: 2, memoryGiB: 0 } as const;
/** Memory caps offered in Hub; 0 means no cap. */
export const DEV_MEMORY_CHOICES = [0, 8, 12, 16] as const;

export type DevResources = { cores: number; testJobs: number; memoryGiB: number };
type DevResourcesState = DevResources & { version: 1; revision: number; actorId: string; appliedAt: string };

function fail(message: string): never {
  throw new Error(message);
}

export const serverCores = (): number => Math.max(1, cpus().length);

export function validDevResources(value: Partial<DevResources>, cores = serverCores()): value is DevResources {
  const { cores: limit, testJobs, memoryGiB } = value;
  return Number.isInteger(limit) && limit! >= 1 && limit! <= cores
    && Number.isInteger(testJobs) && testJobs! >= 1 && testJobs! <= limit!
    && (DEV_MEMORY_CHOICES as readonly number[]).includes(memoryGiB as number);
}

function parse(raw: string): DevResourcesState {
  const value = JSON.parse(raw) as Partial<DevResourcesState>;
  const limits = { cores: value.cores, testJobs: value.testJobs, memoryGiB: value.memoryGiB };
  if (value.version === 1 && Number.isInteger(value.revision) && Number(value.revision) >= 1 && validDevResources(limits, Number.MAX_SAFE_INTEGER)
    && typeof value.actorId === "string" && typeof value.appliedAt === "string") return value as DevResourcesState;
  fail("Development resources state is invalid");
}

export function devResourcesStatePath(home = resolveKuramiHome("/home/shagon1k/_hermes/_kurami")): string {
  return resolve(home, "state/dev-resources.json");
}

export function devSliceUnitPath(): string {
  return resolve(process.env.KURAMI_SYSTEMD_USER_DIR ?? resolve(process.env.XDG_CONFIG_HOME ?? resolve(homedir(), ".config"), "systemd/user"), DEV_SLICE);
}

/** The current limits, or the defaults when none were applied or the file is unusable. Never throws. */
export function readDevResources(path = devResourcesStatePath()): DevResources {
  try { const { cores, testJobs, memoryGiB } = parse(readFileSync(path, "utf8")); return { cores, testJobs, memoryGiB }; }
  catch { return { ...DEV_DEFAULTS }; }
}

async function readState(path: string): Promise<DevResourcesState | null> {
  try { return parse(await readFile(path, "utf8")); }
  catch (error) { if ((error as NodeJS.ErrnoException).code === "ENOENT") return null; throw error; }
}

async function writeAtomically(path: string, content: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  const temporary = `${path}.${process.pid}.tmp`;
  await writeFile(temporary, content, { mode: 0o600 });
  await rename(temporary, path);
}

/** systemd properties for the slice: a CPU cap, a low weight and an optional memory cap. */
export function sliceProperties(limits: DevResources): string[] {
  return [`CPUQuota=${limits.cores * 100}%`, `CPUWeight=${DEV_CPU_WEIGHT}`, `MemoryMax=${limits.memoryGiB ? `${limits.memoryGiB}G` : "infinity"}`];
}

export function sliceUnit(limits: DevResources): string {
  return `# Generated by Kurami (src/system/dev-resources/dev-resources.ts); change it in Hub → Controls → Server.\n[Unit]\nDescription=Kurami development work: Codex workers, tests and builds\n\n[Slice]\n${sliceProperties(limits).join("\n")}\n`;
}

/**
 * Writes the unit (it survives reboots) and applies the same limits to the running slice at once. If systemd
 * refuses, the previous unit is put back, so the file never disagrees with the applied state.
 */
async function applySlice(limits: DevResources): Promise<void> {
  const systemctl = process.env.KURAMI_SYSTEMCTL ?? "systemctl", path = devSliceUnitPath();
  const previous = existsSync(path) ? readFileSync(path, "utf8") : null;
  await writeAtomically(path, sliceUnit(limits));
  try {
    await run(systemctl, ["--user", "daemon-reload"], { timeout: 20_000 });
    await run(systemctl, ["--user", "set-property", "--runtime", DEV_SLICE, ...sliceProperties(limits)], { timeout: 20_000 });
  } catch {
    if (previous === null) await rm(path, { force: true }); else await writeAtomically(path, previous);
    await run(systemctl, ["--user", "daemon-reload"], { timeout: 20_000 }).catch(() => undefined);
    fail("systemd did not accept the development limits");
  }
}

function response(action: "status" | "applied" | "unchanged" | "ensured", state: DevResourcesState | null): Record<string, unknown> {
  const limits = state ? { cores: state.cores, testJobs: state.testJobs, memoryGiB: state.memoryGiB } : { ...DEV_DEFAULTS };
  return { ok: true, action, revision: state?.revision ?? 0, ...limits, serverCores: serverCores(), memoryChoices: DEV_MEMORY_CHOICES, defaults: DEV_DEFAULTS, appliedAt: state?.appliedAt ?? null };
}

export async function runDevResourcesCli(argv = process.argv.slice(2)): Promise<Record<string, unknown>> {
  const args = [...argv], command = args.shift();
  if (command !== "status" && command !== "apply" && command !== "ensure") fail("Usage: dev-resources.ts <status|ensure|apply> [--cores N --test-jobs N --memory-gib N --expected-revision N --actor-id ID]");
  const path = devResourcesStatePath(), previous = await readState(path);
  if (command === "status" || command === "ensure") {
    if (args.length) fail(`Development resources ${command} accepts no arguments`);
    // ensure: the first run on a server writes the slice with the current (or default) limits.
    if (command === "ensure" && !existsSync(devSliceUnitPath())) { await applySlice(readDevResources(path)); return response("ensured", previous); }
    return response("status", previous);
  }
  const options: Record<string, string> = {};
  for (let index = 0; index < args.length; index += 2) {
    const flag = args[index], value = args[index + 1];
    if (!["--cores", "--test-jobs", "--memory-gib", "--expected-revision", "--actor-id"].includes(flag ?? "") || value === undefined) fail(`Unknown development resources argument: ${flag ?? "missing"}`);
    options[flag!.slice(2)] = value;
  }
  const limits = { cores: Number(options.cores), testJobs: Number(options["test-jobs"]), memoryGiB: Number(options["memory-gib"]) };
  if (!validDevResources(limits)) fail(`Invalid limits: cores 1–${serverCores()}, test jobs 1–cores, memory one of ${DEV_MEMORY_CHOICES.join(", ")} GiB`);
  if (!/^\d+$/.test(options["expected-revision"] ?? "")) fail("Invalid expected revision");
  if (!/^\d{1,40}$/.test(options["actor-id"] ?? "")) fail("Invalid actor ID");
  const current = previous?.revision ?? 0;
  if (Number(options["expected-revision"]) !== current) fail(`Development resources changed since this panel opened: expected revision ${options["expected-revision"]}, current revision ${current}`);
  if (previous && previous.cores === limits.cores && previous.testJobs === limits.testJobs && previous.memoryGiB === limits.memoryGiB) return response("unchanged", previous);
  await applySlice(limits);
  const next: DevResourcesState = { version: 1, revision: current + 1, ...limits, actorId: options["actor-id"]!, appliedAt: new Date().toISOString() };
  await writeAtomically(path, `${JSON.stringify(next)}\n`);
  return response("applied", next);
}

if (import.meta.main) {
  runDevResourcesCli().then(result => process.stdout.write(`${JSON.stringify(result)}\n`)).catch((error: unknown) => {
    process.stderr.write(`${JSON.stringify({ ok: false, error: error instanceof Error ? error.message : String(error) })}\n`);
    process.exitCode = 1;
  });
}
